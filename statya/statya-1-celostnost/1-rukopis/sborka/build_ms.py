def table(widths, rows, sz=18, header_rows=1, align=None):
    """rows: список строк, строка — список текстов ячеек (с разметкой, \\n — перенос)."""
    grid = "".join(f'<w:gridCol w:w="{w}"/>' for w in widths)
    out = ['<w:tbl><w:tblPr><w:tblStyle w:val="TableGrid"/><w:tblW w:type="auto" w:w="0"/>'
           '<w:jc w:val="center"/><w:tblLayout w:type="fixed"/><w:tblCellMar>'
           '<w:left w:w="57" w:type="dxa"/><w:right w:w="57" w:type="dxa"/></w:tblCellMar>'
           '<w:tblLook w:firstColumn="1" w:firstRow="1" w:lastColumn="0" w:lastRow="0" '
           f'w:noHBand="0" w:noVBand="1" w:val="04A0"/></w:tblPr><w:tblGrid>{grid}</w:tblGrid>']
    for ri, row in enumerate(rows):
        hdr = ri < header_rows
        out.append("<w:tr><w:trPr><w:cantSplit/>" + ("<w:tblHeader/>" if hdr else "") +
                   "</w:trPr>")
        for ci, (w, cell) in enumerate(zip(widths, row)):
            jc = "center" if hdr else ((align or {}).get(ci, "left"))
            out.append(f'<w:tc><w:tcPr><w:tcW w:type="dxa" w:w="{w}"/></w:tcPr><w:p><w:pPr>'
                       f'<w:spacing w:before="0" w:after="0"/><w:ind w:firstLine="0"/>'
                       f'<w:jc w:val="{jc}"/></w:pPr>{runs(cell, sz, bold=hdr)}</w:p></w:tc>')
        out.append("</w:tr>")
    out.append("</w:tbl>")
    return "".join(out)


