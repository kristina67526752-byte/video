def retitle(path: Path, extra=None):
    d = Document(path)
    for p in d.paragraphs + [p for t in d.tables for r in t.rows for c in r.cells
                             for p in c.paragraphs]:
        if OLD_TITLE in p.text:
            for r in p.runs:
                if OLD_TITLE in r.text:
                    r.text = r.text.replace(OLD_TITLE, NEW_TITLE)
            if OLD_TITLE in p.text:                       # название разбито по runs
                txt = p.text.replace(OLD_TITLE, NEW_TITLE)
                for r in p.runs[1:]:
                    r.text = ""
                p.runs[0].text = txt
        if extra:
            extra(p)
    d.core_properties.title = NEW_TITLE
    d.save(path)


