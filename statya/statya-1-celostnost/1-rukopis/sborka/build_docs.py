def new_doc(landscape=False) -> Document:
    d = Document()
    st = d.styles["Normal"]
    st.font.name = "Times New Roman"
    st.element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    st.font.size = Pt(11)
    st.paragraph_format.space_after = Pt(4)
    sec = d.sections[0]
    sec.page_width, sec.page_height = Cm(21), Cm(29.7)
    if landscape:
        sec.page_width, sec.page_height = Cm(29.7), Cm(21)
        sec.orientation = 1
    for side in ("left_margin", "right_margin", "top_margin", "bottom_margin"):
        setattr(sec, side, Cm(2))
    for lvl, size in ((1, 14), (2, 12)):
        h = d.styles[f"Heading {lvl}"]
        h.font.name, h.font.size, h.font.bold = "Times New Roman", Pt(size), True
        h.font.color.rgb = None
        h.element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
        h.paragraph_format.space_before, h.paragraph_format.space_after = Pt(10), Pt(4)
        h.paragraph_format.keep_with_next = True
    return d


def add(d_or_cell, text: str, bold=False, italic=False, size=None, hl=False, style=None):
    """Абзац с разметкой **полужирный** и ⟦выделение⟧."""
    p = d_or_cell.add_paragraph(style=style)
    for part in re.split(r"(\*\*.*?\*\*|⟦.*?⟧)", text):
        if not part:
            continue
        b, h = bold, hl
        if part.startswith("**"):
            part, b = part[2:-2], True
        elif part.startswith("⟦"):
            part, h = part[1:-1], True
        r = p.add_run(part)
        r.bold, r.italic = b, italic
        if size:
            r.font.size = Pt(size)
        if h:
            r.font.highlight_color = WD_COLOR_INDEX.YELLOW
    return p


def grid(d, widths_cm, rows, size=9.5, header=True):
    t = d.add_table(rows=0, cols=len(widths_cm))
    t.style = "Table Grid"
    t.autofit = False
    tg = t._tbl.tblGrid
    for gc, w in zip(tg.findall(qn("w:gridCol")), widths_cm):
        gc.set(qn("w:w"), str(int(w * 567)))
    for ri, row in enumerate(rows):
        cells = t.add_row().cells
        for ci, (w, txt) in enumerate(zip(widths_cm, row)):
            c = cells[ci]
            c.width = Cm(w)
            c.paragraphs[0].text = ""
            first = True
            for line in str(txt).split("\n"):
                p = c.paragraphs[0] if first else c.add_paragraph()
                first = False
                p.paragraph_format.space_after = Pt(0)
                for part in re.split(r"(\*\*.*?\*\*|⟦.*?⟧)", line):
                    if not part:
                        continue
                    b = header and ri == 0
                    h = False
                    if part.startswith("**"):
                        part, b = part[2:-2], True
                    elif part.startswith("⟦"):
                        part, h = part[1:-1], True
                    r = p.add_run(part)
                    r.bold, r.font.size = b, Pt(size)
                    if h:
                        r.font.highlight_color = WD_COLOR_INDEX.YELLOW
        if header and ri == 0:
            trpr = t.rows[0]._tr.get_or_add_trPr()
            el = OxmlElement("w:tblHeader")
            trpr.append(el)
    return t


def meta(d, title):
    cp = d.core_properties
    cp.title, cp.author, cp.last_modified_by = title, "", ""


