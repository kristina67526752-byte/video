def all_paragraphs(doc):
    yield from doc.paragraphs
    for t in doc.tables:
        seen = set()
        for row in t.rows:
            for c in row.cells:
                if c._tc in seen:
                    continue
                seen.add(c._tc)
                yield from c.paragraphs


def norm(s: str) -> str:
    """Неразрывные и узкие пробелы — как обычные (длина строки не меняется)."""
    return s.replace("\u00a0", " ").replace("\u202f", " ").replace("\u2009", " ")


def replace(doc, old: str, new: str, count: int = 1):
    n = 0
    old = norm(old)
    for p in all_paragraphs(doc):
        i = norm(p.text).find(old)
        if i >= 0:
            text = p.text[:i] + new + p.text[i + len(old):]
            runs = p.runs
            runs[0].text = text
            for r in runs[1:]:
                r.text = ""
            n += 1
    assert n == count, (old[:60], n)


