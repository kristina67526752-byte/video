def norm(s: str) -> str:
    return s.replace(" ", " ").replace(" ", " ").replace(" ", " ")


def all_paragraphs(doc):
    yield from doc.paragraphs
    for t in doc.tables:
        seen = set()
        for row in t.rows:
            for c in row.cells:
                if c._tc in seen:
                    continue
                seen.add(c._tc)
                yield from c.paragraphs


def replace(doc, old: str, new: str, count: int = 1):
    n = 0
    old = norm(old)
    for p in all_paragraphs(doc):
        i = norm(p.text).find(old)
        if i >= 0:
            text = p.text[:i] + new + p.text[i + len(old):]
            runs = p.runs
            runs[0].text = text
            for r in runs[1:]:
                r.text = ""
            n += 1
    assert n == count, (old[:60], n)


def set_par(doc, prefix: str, new: str):
    hits = [p for p in all_paragraphs(doc) if norm(p.text).startswith(norm(prefix))]
    assert len(hits) == 1, (prefix, len(hits))
    runs = hits[0].runs
    runs[0].text = new
    for r in runs[1:]:
        r.text = ""


def new_doc(title: str, intro: str):
    doc = docx.Document()
    st = doc.styles["Normal"]
    st.font.name = "Times New Roman"
    st.font.size = Pt(11)
    for s in doc.sections:
        s.left_margin = s.right_margin = Cm(2)
        s.top_margin = s.bottom_margin = Cm(2)
    h = doc.add_paragraph()
    r = h.add_run(title)
    r.bold = True
    r.font.size = Pt(14)
    h.alignment = WD_ALIGN_PARAGRAPH.CENTER
    doc.add_paragraph(intro)
    return doc


def table(doc, head: tuple, rows: list[tuple], widths: tuple):
    t = doc.add_table(rows=1, cols=len(head))
    t.style = "Table Grid"
    for c, s in zip(t.rows[0].cells, head):
        c.text = ""
        c.paragraphs[0].add_run(s).bold = True
    for row in rows:
        cells = t.add_row().cells
        for c, s in zip(cells, row):
            c.text = s
    for row in t.rows:
        for c, w in zip(row.cells, widths):
            c.width = Cm(w)
            for p in c.paragraphs:
                for r in p.runs:
                    r.font.size = Pt(10)


def heading(doc, text: str):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(12)
    p.add_run(text).bold = True


