"""
Физические постоянные (СИ) и параметры плазмы.

Во всём проекте используются ТОЛЬКО единицы СИ:
    длина — м, время — с, скорость — м/с, масса — кг, заряд — Кл,
    напряжённость поля — В/м, концентрация — м⁻³, температура — К,
    частота — рад/с (циклическая) или Гц, волновое число — рад/м,
    плотность энергии — Дж/м³.

Значения постоянных — CODATA-2018 (e, k_B и c в СИ с 2019 г. заданы точно).
"""
from __future__ import annotations

import numpy as np

E_CHARGE = 1.602176634e-19      # элементарный заряд e, Кл (точно)
M_E = 9.1093837015e-31          # масса электрона m_e, кг
EPS0 = 8.8541878128e-12         # электрическая постоянная ε₀, Ф/м
K_B = 1.380649e-23              # постоянная Больцмана k_B, Дж/К (точно)
C_LIGHT = 299792458.0           # скорость света c, м/с (точно)
M_P = 1.67262192369e-27         # масса протона m_p, кг
AMU = 1.66053906660e-27         # атомная единица массы, кг

# Однозарядные ионы: название → масса, кг (масса атома минус масса электрона)
IONS = {
    "H+": M_P,                              # водород (протон), m_i/m_e = 1836.15
    "D+": 3.3435837724e-27,                 # дейтерий
    "He+": 4.002602 * AMU - M_E,            # гелий
    "Ar+": 39.948 * AMU - M_E,              # аргон
    "O+": 15.999 * AMU - M_E,               # кислород (ионосфера)
}
ION_LABEL = {"none": "неподвижны", "H+": "H⁺", "D+": "D⁺", "He+": "He⁺", "Ar+": "Ar⁺", "O+": "O⁺"}


# --------------------------------------------------------------------------
# Основные параметры плазмы (все аргументы и результаты — в СИ)
# --------------------------------------------------------------------------
def plasma_frequency(n, m=M_E, q=E_CHARGE):
    """Плазменная частота ω_p = √(n q²/(ε₀ m)), рад/с."""
    return np.sqrt(n * q * q / (EPS0 * m))


def thermal_velocity(T, m=M_E):
    """Тепловая скорость v_T = √(k_B T/m), м/с (среднеквадратичная по одной оси)."""
    return np.sqrt(K_B * T / m)


def debye_length(n, T):
    """Дебаевский радиус λ_D = √(ε₀ k_B T/(n e²)) = v_Te/ω_pe, м."""
    return np.sqrt(EPS0 * K_B * T / (n * E_CHARGE ** 2))


def lorentz_gamma(v):
    """Лоренц-фактор γ = 1/√(1 − v²/c²)."""
    return 1.0 / np.sqrt(1.0 - (np.asarray(v, dtype=float) / C_LIGHT) ** 2)


def kinetic_energy(v, m=M_E):
    """Релятивистская кинетическая энергия частицы (γ − 1)mc², Дж.
    Записана как m u²/(γ + 1), u = γv — так нет потери точности при v ≪ c."""
    g = lorentz_gamma(v)
    u = g * np.asarray(v, dtype=float)
    return m * u * u / (g + 1.0)


def ion_sound_speed(T_e, T_i, m_i):
    """Скорость ионного звука c_s = √(k_B(T_e + 3T_i)/m_i), м/с."""
    return np.sqrt(K_B * (T_e + 3.0 * T_i) / m_i)


def coulomb_logarithm(n, T_e):
    """Кулоновский логарифм ln Λ = ln(12π n λ_D³) (классическая формула, T_e ≲ 10⁵ К)."""
    return float(np.log(max(12.0 * np.pi * n * debye_length(n, T_e) ** 3, np.e)))


def collision_frequency_ei(n, T_e):
    """Частота электрон-ионных столкновений (Спитцер–Брагинский, Z = 1), с⁻¹:
        ν_ei = √2 n e⁴ lnΛ / (12 π^{3/2} ε₀² √m_e (k_B T_e)^{3/2})."""
    lnL = coulomb_logarithm(n, T_e)
    return (np.sqrt(2.0) * n * E_CHARGE ** 4 * lnL
            / (12.0 * np.pi ** 1.5 * EPS0 ** 2 * np.sqrt(M_E) * (K_B * T_e) ** 1.5))


def landau_damping_rate(k, n, T_e):
    """Декремент затухания Ландау ленгмюровской волны на электронах плазмы, с⁻¹:
        γ_L = √(π/8) · ω_p/(kλ_D)³ · exp(−1/(2k²λ_D²) − 3/2).
    Формула верна при kλ_D ≲ 0.4; при kλ_D → 0 затухание экспоненциально мало."""
    k = np.abs(np.asarray(k, dtype=float))
    wp = plasma_frequency(n)
    kl = np.maximum(k * debye_length(n, T_e), 1e-12)
    with np.errstate(over="ignore", under="ignore"):
        g = np.sqrt(np.pi / 8.0) * wp / kl ** 3 * np.exp(-0.5 / kl ** 2 - 1.5)
    return np.minimum(g, wp)          # при kλ_D ~ 1 формула не работает: ограничиваем ω_p
